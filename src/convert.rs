#[derive(Debug, PartialEq, Eq)]
pub(crate) enum KeyPress {
    Press,
    UnPress,
}

pub(crate) fn iced_key_to_cef_key(
    press: KeyPress,
    modified_key: Option<&keyboard::Key>,
    key: Option<&keyboard::Key>,
    physical_key: Option<&keyboard::key::Physical>,
    modifiers: &keyboard::Modifiers,
    text: &Option<iced_core::SmolStr>,
    location: keyboard::Location,
) -> Option<(cef::KeyEvent, bool)> {
    let mut modifiers_ = cef::sys::cef_event_flags_t::EVENTFLAG_NONE;
    let mut cef_keyevent = cef::KeyEvent {
        type_: match press {
            KeyPress::Press => cef::sys::cef_key_event_type_t::KEYEVENT_RAWKEYDOWN,
            KeyPress::UnPress => cef::sys::cef_key_event_type_t::KEYEVENT_KEYUP,
        }
        .into(),
        is_system_key: false as _,
        ..Default::default()
    };

    if modifiers.control() {
        modifiers_ |= cef::sys::cef_event_flags_t::EVENTFLAG_CONTROL_DOWN;
    }
    if modifiers.alt() {
        modifiers_ |= cef::sys::cef_event_flags_t::EVENTFLAG_ALT_DOWN;
        #[cfg(target_os = "windows")]
        {
            cef_keyevent.is_system_key = true as _;
        }
    }
    if modifiers.shift() {
        modifiers_ |= cef::sys::cef_event_flags_t::EVENTFLAG_SHIFT_DOWN;
    }
    if modifiers.logo() {
        modifiers_ |= cef::sys::cef_event_flags_t::EVENTFLAG_COMMAND_DOWN;
    }
    /*
    if modifiers.num_lock() {
        modifiers_ |= cef::sys::cef_event_flags_t::EVENTFLAG_NUM_LOCK_ON;
    }
    if modifiers.caps_lock() {
        modifiers_ |= cef::sys::cef_event_flags_t::EVENTFLAG_CAPS_LOCK_ON;
    }
    */

    match location {
        keyboard::Location::Left => modifiers_ |= cef::sys::cef_event_flags_t::EVENTFLAG_IS_LEFT,
        keyboard::Location::Right => modifiers_ |= cef::sys::cef_event_flags_t::EVENTFLAG_IS_RIGHT,
        keyboard::Location::Standard => modifiers_ |= cef::sys::cef_event_flags_t::EVENTFLAG_NONE,
        keyboard::Location::Numpad => {
            modifiers_ |= cef::sys::cef_event_flags_t::EVENTFLAG_IS_KEY_PAD
        }
    }
    let is_arrow_key = matches!(
        modified_key,
        Some(Key::Named(
            Named::ArrowDown | Named::ArrowUp | Named::ArrowLeft | Named::ArrowRight
        ))
    );

    cef_keyevent.native_key_code = match physical_key {
        Some(keyboard::key::Physical::Code(code)) => to_scancode(*code) as _,
        _ => 0,
    };
    cef_keyevent.windows_key_code = match modified_key {
        Some(Key::Named(named)) => named_key_to_virtual_keycode(*named) as _,
        Some(Key::Character(c)) => {
            ascii_to_virtual_keycode(c.chars().next().unwrap_or_default()) as _
        }
        _ => 0,
    };

    cef_keyevent.modifiers = modifiers_.0 as _;
    cef_keyevent.character = match text {
        Some(text) => text.chars().next().unwrap_or_default() as _,
        None => 0,
    };
    cef_keyevent.unmodified_character = match &key {
        Some(Key::Character(c)) => c.chars().next().unwrap_or_default() as _,
        Some(Key::Named(named)) => named_key_to_text(*named).unwrap_or_default() as _,
        _ => 0,
    };

    let should_send_char = || {
        if matches!(press, KeyPress::UnPress) || is_arrow_key {
            return false;
        };
        match key {
            Some(Key::Named(named)) => !matches!(
                named,
                Named::Control | Named::Meta | Named::CapsLock | Named::Alt | Named::Shift
            ),
            _ => true,
        }
    };

    Some((cef_keyevent, should_send_char()))
}

fn named_key_to_text(named_key: Named) -> Option<char> {
    match named_key {
        Named::Enter => Some('\r'),
        Named::Backspace => Some('\x08'),
        Named::Tab => Some('\t'),
        Named::Space => Some(' '),
        Named::Escape => Some('\x1b'),
        _ => None,
    }
}

